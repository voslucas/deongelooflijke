"""Generate and store rich biographical descriptions for podcast guests.

Writes a `bio` field into data/persons/{slug}.json, creating the file if needed.
The bio is generated by Claude using all available data sources for that guest:
  - Feed show-notes for each episode the guest appeared in
  - LLM analysis summaries (summary_tldr + summary_points) for those episodes
  - Selected guest transcript segments (what the guest says about themselves)

Usage:
    python scripts/enrich_guest_bios.py --guest paul-schenderling
    python scripts/enrich_guest_bios.py --all-missing
    python scripts/enrich_guest_bios.py --all-missing --force   # overwrite existing bios
    python scripts/enrich_guest_bios.py --guest tim-hofman --model claude-haiku-5-5

Reads:
    data/episodes.json              master guest/episode list
    data/feed/{n}.json              feed snapshot with show-notes
    data/analysis/{n}.json          LLM analysis (summaries, themes)
    data/transcripts/{n}.json       speaker-diarised transcripts
    data/persons/{slug}.json        existing person file (socials, img)

Writes:
    data/persons/{slug}.json        adds / updates `bio` field

Requires:
    pip install anthropic
    ANTHROPIC_API_KEY env var (or ant auth login profile)
"""
import argparse, json, os, pathlib, re, sys, unicodedata

ROOT           = pathlib.Path(__file__).resolve().parent.parent
DIR_FEED       = ROOT / 'data' / 'feed'
DIR_ANALYSIS   = ROOT / 'data' / 'analysis'
DIR_TRANSCRIPTS= ROOT / 'data' / 'transcripts'
DIR_PERSONS    = ROOT / 'data' / 'persons'
EPISODES_JSON  = ROOT / 'data' / 'episodes.json'

# Haiku is sufficient here: the task is synthesis of well-structured context into
# 2-3 sentences, not reasoning or extraction. Much cheaper for 200+ guests.
DEFAULT_MODEL           = 'claude-haiku-5-5'
# Max chars of transcript segments per episode to include in the prompt
MAX_TRANSCRIPT_PER_EP   = 3_000
# Max total chars for all transcript material across all episodes
MAX_TRANSCRIPT_TOTAL    = 12_000


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def slug(name: str) -> str:
    s = unicodedata.normalize('NFD', name.lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')


def _load_json(path: pathlib.Path) -> dict | None:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding='utf-8'))


def _ep_key(ep: dict) -> str:
    return str(ep['n']) if ep.get('n') is not None else 'x' + ep['id']


def _guest_transcript_segments(tr: dict, guest_name: str) -> str:
    """Return up to MAX_TRANSCRIPT_PER_EP chars of the guest's own speech."""
    # Build speaker-id → name map
    speaker_map = {sp['id']: sp['name'] for sp in tr.get('speakers', [])}
    lines = []
    for seg in tr.get('segments', []):
        name = speaker_map.get(seg.get('speaker', ''), '')
        if name != guest_name:
            continue
        text = seg.get('text', '').strip()
        if not text:
            continue
        mm, ss = divmod(int(seg.get('start', 0)), 60)
        lines.append(f'[{mm:02d}:{ss:02d}] {text}')

    full = '\n'.join(lines)
    return full[:MAX_TRANSCRIPT_PER_EP]


def _build_prompt(guest_name: str, episodes: list[dict]) -> str:
    """Build the user prompt with all episode context for this guest."""
    parts = [
        f'Schrijf een korte biografie van **{guest_name}**.\n\n'
        f'REGELS:\n'
        f'- 2 à 3 zinnen, encyclopedische stijl\n'
        f'- Nederlands, derde persoon, tegenwoordige tijd\n'
        f'- Begin met de naam van de persoon\n'
        f'- Beschrijf wie de persoon is: beroep, vakgebied, eventueel achtergrond of levensbeschouwing\n'
        f'- De site toont zelf al wanneer en hoe vaak iemand te gast was: zeg dat NIET\n'
        f'- Geen afleveringsnummers, geen datums, geen titels van afleveringen\n'
        f'- Geen samenvatting van wat er besproken werd in een aflevering\n'
        f'- Geen URL\'s, geen aanhalingstekens om de tekst, geen opmaak\n\n'
        f'Gebruik de onderstaande bronnen alleen om te begrijpen wie de persoon is — '
        f'niet om afleveringen te beschrijven.\n\n'
        f'---\n\n'
        f'BRONNEN ({len(episodes)} afleveringen):\n\n'
    ]

    for ep in episodes:
        key = _ep_key(ep)
        parts.append(f'### Aflevering #{ep["n"]} – {ep["t"]} ({ep["d"][:10]})\n')

        # Feed show-notes
        feed = _load_json(DIR_FEED / f'{key}.json')
        if feed and feed.get('desc'):
            desc = feed['desc'].replace('\n', ' ').strip()
            parts.append(f'**Shownotes:** {desc[:600]}\n\n')

        # Analysis summary
        analysis = _load_json(DIR_ANALYSIS / f'{key}.json')
        if analysis:
            tldr = analysis.get('summary_tldr', '')
            if tldr:
                parts.append(f'**Samenvatting:** {tldr}\n')
            points = analysis.get('summary_points', [])
            if points:
                parts.append('**Kernpunten:** ' + ' · '.join(points[:5]) + '\n')
            themes = analysis.get('themes', [])
            if themes:
                parts.append(f'**Thema\'s:** {", ".join(themes)}\n')
            parts.append('\n')

        # Transcript excerpts (guest speech only)
        tr = _load_json(DIR_TRANSCRIPTS / f'{key}.json')
        if tr:
            excerpt = _guest_transcript_segments(tr, guest_name)
            if excerpt:
                parts.append(f'**Fragment (eigen woorden van de gast):**\n{excerpt}\n\n')

    prompt = ''.join(parts)

    # Safety cap: keep total prompt manageable
    if len(prompt) > 80_000:
        prompt = prompt[:80_000] + '\n\n[context ingekort]'

    return prompt


def _call_llm(client, model: str, prompt: str) -> str:
    system = (
        'Je bent een redacteur van De Ongelooflijke Podcast, een Nederlandse podcast '
        'over geloof, zingeving en maatschappij op NPO Radio 1 / EO. '
        'Schrijf beknopte, informatieve gastbeschrijvingen op basis van de gegeven context. '
        'Schrijf alleen de gevraagde tekst, niets anders.'
    )
    # 2000 tokens: haiku-5-5 uses extended thinking and needs headroom for
    # the thinking block before it can emit the short text response.
    response = client.messages.create(
        model=model,
        max_tokens=2000,
        system=system,
        messages=[{'role': 'user', 'content': prompt}],
    )
    return next((b.text for b in response.content if b.type == 'text'), '').strip()


def _load_or_create_person(sl: str) -> dict:
    p = DIR_PERSONS / f'{sl}.json'
    if p.exists():
        return json.loads(p.read_text(encoding='utf-8'))
    return {}


def _save_person(sl: str, data: dict) -> None:
    DIR_PERSONS.mkdir(parents=True, exist_ok=True)
    p = DIR_PERSONS / f'{sl}.json'
    p.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')


# ---------------------------------------------------------------------------
# Main logic
# ---------------------------------------------------------------------------

def enrich_guest(client, model: str, guest_name: str, force: bool = False) -> bool:
    """Generate and store a bio for one guest. Returns True if written."""
    sl = slug(guest_name)
    person = _load_or_create_person(sl)

    if person.get('bio') and not force:
        print(f'  skip {guest_name!r} — bio already present (use --force to overwrite)')
        return False

    # Load all episodes for this guest from episodes.json
    all_eps = json.loads(EPISODES_JSON.read_text(encoding='utf-8'))['eps']
    # Hosts David Boogerd and Stefan Paas appear in every episode; don't use 'g' for them
    is_host = guest_name in ('David Boogerd', 'Stefan Paas')
    if is_host:
        guest_eps = [e for e in all_eps if e.get('f') not in ('Trailer', 'Spin-off')]
    else:
        guest_eps = [e for e in all_eps if guest_name in e.get('g', [])]

    if not guest_eps:
        print(f'  skip {guest_name!r} — no episodes found')
        return False

    # Sort by date ascending (oldest first gives narrative chronology)
    guest_eps = sorted(guest_eps, key=lambda e: e.get('d', ''))

    print(f'  generating bio for {guest_name!r} ({len(guest_eps)} episodes) …')
    prompt = _build_prompt(guest_name, guest_eps)
    bio = _call_llm(client, model, prompt)

    if not bio:
        print(f'  ERROR: empty response for {guest_name!r}')
        return False

    person['bio'] = bio
    _save_person(sl, person)
    print(f'  wrote {sl}.json — {len(bio)} chars')
    print(f'  bio: {bio[:120]}…' if len(bio) > 120 else f'  bio: {bio}')
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description='Enrich guest bios using Claude.')
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--guest', metavar='SLUG_OR_NAME',
                       help='Slug or exact name of a single guest to process')
    group.add_argument('--all-missing', action='store_true',
                       help='Process all guests who have no bio in persons/*.json')
    group.add_argument('--all', action='store_true',
                       help='Process every guest (implies --force)')
    parser.add_argument('--force', action='store_true',
                        help='Overwrite existing bios')
    parser.add_argument('--model', default=DEFAULT_MODEL,
                        help=f'Claude model (default: {DEFAULT_MODEL})')
    args = parser.parse_args()

    try:
        import anthropic
    except ImportError:
        sys.exit('anthropic package not found — run: pip install anthropic')

    # Load .env from repo root if present (same as analyze_episode.py)
    env_path = ROOT / '.env'
    if env_path.exists():
        for line in env_path.read_text(encoding='utf-8').splitlines():
            line = line.strip()
            if line and not line.startswith('#') and '=' in line:
                k, _, v = line.partition('=')
                os.environ.setdefault(k.strip(), v.strip())

    api_key = os.environ.get('ANTHROPIC_API_KEY') or os.environ.get('CLAUDE_API_KEY')
    client = anthropic.Anthropic(api_key=api_key) if api_key else anthropic.Anthropic()

    # Build guest list
    all_eps_data = json.loads(EPISODES_JSON.read_text(encoding='utf-8'))
    all_eps = all_eps_data['eps']

    # Collect all unique guest names from episode data
    guest_names: set[str] = set()
    for ep in all_eps:
        for g in ep.get('g', []):
            guest_names.add(g)
    # Hosts treated separately: they're not in 'g' but have person pages
    for host in ('David Boogerd', 'Stefan Paas'):
        guest_names.add(host)

    if args.guest:
        # Accept either a slug or an exact name
        target = args.guest
        # Try exact name match first
        matched = [n for n in guest_names if n == target]
        if not matched:
            # Try slug match
            target_slug = slug(target)
            matched = [n for n in guest_names if slug(n) == target_slug]
        if not matched:
            sys.exit(f'Guest not found: {target!r}\nKnown guests (sample): '
                     + ', '.join(sorted(guest_names)[:10]))
        process_names = matched
        force = True  # explicit guest always rewrites

    elif args.all or args.all_missing:
        force = args.force or args.all
        process_names = sorted(guest_names)

    written = 0
    for name in process_names:
        sl = slug(name)
        if args.all_missing and not args.force:
            person = _load_or_create_person(sl)
            if person.get('bio'):
                continue  # already has bio, skip
        try:
            if enrich_guest(client, args.model, name, force=force):
                written += 1
        except Exception as exc:
            print(f'  ERROR processing {name!r}: {exc}')

    print(f'\nDone — {written} bio(s) written.')
    if written:
        print('Run: python scripts/4_split_data.py && python scripts/5_build_site.py')


if __name__ == '__main__':
    main()
